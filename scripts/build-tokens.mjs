// Reads tokens/tokens.json and writes:
//   1. tokens/theme.css         — drop-in CSS for any Tailwind v4 project
//   2. registry.json → "theme"  — cssVars the shadcn CLI merges into consumers' CSS
// Run: npm run tokens
import { readFileSync, writeFileSync } from "node:fs";

const root = new URL("..", import.meta.url);
const tokens = JSON.parse(readFileSync(new URL("tokens/tokens.json", root), "utf8"));
const { light, dark, theme } = tokens;

const block = (sel, vars) =>
  `${sel} {\n${Object.entries(vars).map(([k, v]) => `  --${k}: ${v};`).join("\n")}\n}`;

// Every color token gets a Tailwind utility (bg-primary, text-success, ...)
const colorKeys = Object.keys(light).filter((k) => k !== "radius");
const inline = {
  ...Object.fromEntries(colorKeys.map((k) => [`color-${k}`, `var(--${k})`])),
  ...theme,
};

const css = [
  "/* GENERATED by scripts/build-tokens.mjs — edit tokens/tokens.json instead. */",
  '@import "tailwindcss";',
  "",
  "@custom-variant dark (&:is(.dark *));",
  "",
  block(":root", light),
  "",
  block(".dark", dark),
  "",
  block("@theme inline", inline),
  "",
  "@layer base {\n  * { border-color: var(--border); outline-color: color-mix(in oklch, var(--ring) 50%, transparent); }\n  html { font-family: var(--font-sans); }\n  body { background: var(--background); color: var(--foreground); font-family: var(--font-sans); }\n  button:not(:disabled), [role=\"button\"]:not(:disabled) { cursor: pointer; }\n}",
  "",
].join("\n");
writeFileSync(new URL("tokens/theme.css", root), css);

const regUrl = new URL("registry.json", root);
const registry = JSON.parse(readFileSync(regUrl, "utf8"));
const item = registry.items.find((i) => i.name === "theme");
if (!item) throw new Error('registry.json has no "theme" item');
item.cssVars = { theme, light, dark };
item.registryDependencies = ["font-dm-sans"];
// Do not @import a font stylesheet here. The CLI appends it after
// @import "shadcn/tailwind.css", and Tailwind then emits the import after
// real rules, which is invalid CSS. font-dm-sans loads DM Sans via next/font.
item.css = {
  "@layer base": {
    "button:not(:disabled), [role='button']:not(:disabled)": {
      cursor: "pointer",
    },
  },
};
writeFileSync(regUrl, JSON.stringify(registry, null, 2) + "\n");

console.log(`✔ tokens: ${colorKeys.length} colors → tokens/theme.css + registry.json#theme`);
