// Reads tokens/tokens.json and writes:
//   1. tokens/theme.css           — drop-in CSS for the default theme
//   2. tokens/jazzfolio.css       — drop-in CSS for the dark-only Jazzfolio theme
//   3. registry.json theme items  — cssVars the shadcn CLI merges into consumers
// Run: npm run tokens
import { readFileSync, writeFileSync } from "node:fs"

const root = new URL("..", import.meta.url)
const tokens = JSON.parse(readFileSync(new URL("tokens/tokens.json", root), "utf8"))
const { light, dark, theme, jazzfolio } = tokens

const block = (sel, vars) =>
  `${sel} {\n${Object.entries(vars).map(([k, v]) => `  --${k}: ${v};`).join("\n")}\n}`

function inlineTheme(palette, type) {
  const colorKeys = Object.keys(palette).filter((key) => key !== "radius")
  return {
    ...Object.fromEntries(colorKeys.map((key) => [`color-${key}`, `var(--${key})`])),
    ...type,
  }
}

const baseLayer =
  "@layer base {\n  * { border-color: var(--border); outline-color: color-mix(in oklch, var(--ring) 50%, transparent); }\n  html { font-family: var(--font-sans); }\n  body { background: var(--background); color: var(--foreground); font-family: var(--font-sans); }\n  button:not(:disabled), [role=\"button\"]:not(:disabled) { cursor: pointer; }\n}"

const css = [
  "/* GENERATED by scripts/build-tokens.mjs — edit tokens/tokens.json instead. */",
  '@import "tailwindcss";',
  "",
  "@custom-variant dark (&:is(.dark *));",
  "",
  block(":root", light),
  "",
  block(".dark", dark),
  "",
  block("@theme inline", inlineTheme(light, theme)),
  "",
  baseLayer,
  "",
].join("\n")
writeFileSync(new URL("tokens/theme.css", root), css)

const { radius, ...jazzPalette } = jazzfolio.colors
const jazzRoot = { ...jazzPalette, radius }
const jazzInline = inlineTheme(jazzRoot, jazzfolio.theme)
const heroFade =
  "linear-gradient(to bottom, var(--hero, var(--primary)) 0%, var(--background) 100%)"
const posterFade =
  "linear-gradient(to top, var(--background) 0%, color-mix(in oklch, var(--background) 72%, transparent) 46%, transparent 100%)"

const jazzCss = [
  "/* GENERATED by scripts/build-tokens.mjs — edit tokens/tokens.json instead. */",
  "/* Jazzfolio is dark-only. Accent #3D7BFF on #0A0A0B. Display: Barlow Condensed. Body: Inter. */",
  '@import "tailwindcss";',
  "",
  "@custom-variant dark (&:is(.dark *));",
  "",
  block(":root", jazzRoot),
  "",
  block(".dark", jazzPalette),
  "",
  block("@theme inline", jazzInline),
  "",
  "@utility bg-hero-fade {",
  `  background-image: ${heroFade};`,
  "}",
  "",
  "@utility bg-poster-fade {",
  `  background-image: ${posterFade};`,
  "}",
  "",
  baseLayer.replace(
    "html { font-family: var(--font-sans); }",
    "html { color-scheme: dark; font-family: var(--font-sans); }"
  ),
  "",
  "/* Pill buttons and AA focus, after utilities so they win. */",
  "[data-slot=\"button\"] { border-radius: var(--radius-pill); }",
  "[data-slot=\"button\"][data-variant=\"default\"]:hover { background-color: var(--primary-hover); color: var(--primary-foreground); }",
  "[data-slot=\"button\"][data-variant=\"default\"]:active { background-color: var(--primary-active); color: var(--primary-foreground); }",
  "[data-slot=\"button\"]:focus-visible { outline: 2px solid var(--ring); outline-offset: 2px; box-shadow: none; }",
  "",
].join("\n")
writeFileSync(new URL("tokens/jazzfolio.css", root), jazzCss)

function declarations(vars) {
  return Object.fromEntries(Object.entries(vars).map(([key, value]) => [`--${key}`, value]))
}

const jazzRegistryCss = {
  ":root": declarations(jazzRoot),
  ".dark": declarations(jazzPalette),
  "@utility bg-hero-fade": { "background-image": heroFade },
  "@utility bg-poster-fade": { "background-image": posterFade },
  "[data-slot='button']": { "border-radius": "var(--radius-pill)" },
  "[data-slot='button'][data-variant='default']:hover": {
    "background-color": "var(--primary-hover)",
    color: "var(--primary-foreground)",
  },
  "[data-slot='button'][data-variant='default']:active": {
    "background-color": "var(--primary-active)",
    color: "var(--primary-foreground)",
  },
  "[data-slot='button']:focus-visible": {
    outline: "2px solid var(--ring)",
    "outline-offset": "2px",
    "box-shadow": "none",
  },
  "@layer base": {
    html: { "color-scheme": "dark" },
    "button:not(:disabled), [role='button']:not(:disabled)": { cursor: "pointer" },
  },
}

const regUrl = new URL("registry.json", root)
const registry = JSON.parse(readFileSync(regUrl, "utf8"))
const item = registry.items.find((entry) => entry.name === "theme")
if (!item) throw new Error('registry.json has no "theme" item')
item.cssVars = { theme, light, dark }
item.registryDependencies = ["font-dm-sans"]
// Do not @import a font stylesheet here. The CLI appends it after
// @import "shadcn/tailwind.css", and Tailwind then emits the import after
// real rules, which is invalid CSS. font-dm-sans loads DM Sans via next/font.
item.css = {
  "@layer base": {
    "button:not(:disabled), [role='button']:not(:disabled)": {
      cursor: "pointer",
    },
  },
}

function upsert(name, next, after) {
  const index = registry.items.findIndex((entry) => entry.name === name)
  if (index === -1) {
    const anchor = registry.items.findIndex((entry) => entry.name === after)
    registry.items.splice(anchor === -1 ? registry.items.length : anchor + 1, 0, next)
    return
  }
  registry.items[index] = next
}

upsert(
  "font-barlow-condensed",
  {
    name: "font-barlow-condensed",
    type: "registry:font",
    title: "Barlow Condensed",
    description:
      "Condensed grotesque for Jazzfolio display type. Sentence case at 600 and 700. The CLI wires it to --font-heading and does not restyle body copy.",
    font: {
      family: "'Barlow Condensed', 'Arial Narrow', sans-serif",
      provider: "google",
      import: "Barlow_Condensed",
      variable: "--font-heading",
      weight: ["600", "700"],
      subsets: ["latin"],
      dependency: "@fontsource/barlow-condensed",
    },
  },
  "theme"
)

upsert(
  "theme-jazzfolio",
  {
    name: "theme-jazzfolio",
    type: "registry:theme",
    title: "Jazzfolio theme",
    description:
      "Dark-only theme for live-jazz discovery. Near-black surfaces, electric blue #3D7BFF (AA on #0A0A0B), Inter for body, Barlow Condensed for display in sentence case, 1.75rem poster radius, and pill buttons. Installing it overwrites color, radius, and type tokens. Generated from tokens/tokens.json — do not edit cssVars by hand.",
    cssVars: {
      theme: jazzfolio.theme,
      light: jazzRoot,
      dark: jazzPalette,
    },
    registryDependencies: [
      "font-inter",
      "ajbridges/design-system/font-barlow-condensed#v0.2.0",
    ],
    files: [
      {
        path: "tokens/jazzfolio.css",
        type: "registry:file",
        target: "app/jazzfolio.css",
      },
    ],
    docs: "Jazzfolio is dark in both color schemes. Display text uses font-heading (Barlow Condensed) in sentence case — do not set uppercase. Poster washes use bg-hero-fade (artist color or primary into the background) and bg-poster-fade (image into black). Button labels on the blue are near-black so they clear WCAG AA; white on #3D7BFF does not. If your global CSS still shows the default theme, import app/jazzfolio.css after it.",
    css: jazzRegistryCss,
  },
  "font-barlow-condensed"
)

writeFileSync(regUrl, JSON.stringify(registry, null, 2) + "\n")

const colorCount = Object.keys(jazzPalette).length
console.log(`✔ tokens: default theme + jazzfolio (${colorCount} colors) → theme.css, jazzfolio.css, registry.json`)
